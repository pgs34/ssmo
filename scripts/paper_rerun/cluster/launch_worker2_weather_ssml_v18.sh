run_logged_job \
  "worker2/weather_ssml_v18" \
  "$LOG_DIR/weather_ssml_v18_gpu${TIME_SERIES_GPU:-0}.log" \
  bash scripts/paper_rerun/run_time_series_weather_ssml_v18.sh

