#!/usr/bin/env bash
set -euo pipefail

source "$(cd "$(dirname "${BASH_SOURCE[0]}")/../common" && pwd)/_common.sh"

POOL_OUTPUT_DIR="${POOL_OUTPUT_DIR:-$ROOT_DIR/results/classification_cifar100_bestckpt_pool_cifarstem_v1/classification}"
INDEPENDENT_OUTPUT_DIR="${INDEPENDENT_OUTPUT_DIR:-$ROOT_DIR/results/classification_cifar100_cifarstem_followup_v1/cifarstem_independent_v1}"
DML_OUTPUT_DIR="${DML_OUTPUT_DIR:-$ROOT_DIR/results/classification_cifar100_cifarstem_followup_v1/cifarstem_dml_v1}"
SSML_OUTPUT_DIR="${SSML_OUTPUT_DIR:-$ROOT_DIR/results/classification_cifar100_cifarstem_followup_v1/oxtra42_cifarstem_v1}"
LOG_DIR="${LOG_DIR:-$ROOT_DIR/logs/cifar100_cifarstem}"
POOL_TEMPLATE="${POOL_TEMPLATE:-}"
CUDA_DEVICES="${CUDA_VISIBLE_DEVICES:-${GPU:-0}}"
CIFAR100_STAGE_MAX_PARALLEL_RUNS="${CIFAR100_STAGE_MAX_PARALLEL_RUNS:-all}"

if [[ -z "$POOL_TEMPLATE" ]]; then
  POOL_TEMPLATE="$POOL_OUTPUT_DIR/classification/cifar100/{model}_independent_kl_seed{seed}/best_model.pt"
fi

COMMON_CLASSIFICATION_ENV=(
  CUDA_VISIBLE_DEVICES="$CUDA_DEVICES"
  DATASETS="${DATASETS:-cifar100}"
  MODEL_PAIRS="${MODEL_PAIRS:-resnet34_cifar_gelu:resnet34_cifar_gelu}"
  INDEPENDENT_MODELS="${INDEPENDENT_MODELS:-resnet34_cifar_gelu}"
  REQUIRE_DISTINCT_PEER="${REQUIRE_DISTINCT_PEER:-0}"
  LABEL_NOISE_CONDITIONS="${LABEL_NOISE_CONDITIONS:-none:0.0}"
  SEEDS="${SEEDS:-0 1 2}"
  EPOCHS="${EPOCHS:-100}"
  DEVICE="${DEVICE:-cuda}"
  DOWNLOAD="${DOWNLOAD:-1}"
  OPTIMIZER="${OPTIMIZER:-sgd_nesterov}"
  MOMENTUM="${MOMENTUM:-0.9}"
  LR="${LR:-0.05}"
  WEIGHT_DECAY="${WEIGHT_DECAY:-0.0005}"
  LR_SCHEDULER="${LR_SCHEDULER:-cosine}"
  SCHEDULER_WARMUP_EPOCHS="${SCHEDULER_WARMUP_EPOCHS:-5}"
  SCHEDULER_MIN_SCALE="${SCHEDULER_MIN_SCALE:-0.10}"
  LABEL_SMOOTHING="${LABEL_SMOOTHING:-0.1}"
  MODEL_EMA_DECAY="${MODEL_EMA_DECAY:-0.999}"
  GRAD_CLIP="${GRAD_CLIP:-1.0}"
  TRAIN_AUG_MODE="${TRAIN_AUG_MODE:-strong}"
  FREEZE_BN_STATS="${FREEZE_BN_STATS:-1}"
  CLASSIFICATION_IMITATION_LOSS="${CLASSIFICATION_IMITATION_LOSS:-kl}"
)

run_locked_job "cifar100_cifarstem_pool" "cifar100.pool" "$LOG_DIR/pool.log" env \
  "${COMMON_CLASSIFICATION_ENV[@]}" \
  OUTPUT_DIR="$POOL_OUTPUT_DIR" \
  METHODS="${METHODS:-independent}" \
  BATCH_SIZE="${BATCH_SIZE:-1536}" \
  NUM_WORKERS="${NUM_WORKERS:-4}" \
  bash "$ROOT_DIR/scripts/common/run_core_classification.sh"

parallel_exec_init "$CIFAR100_STAGE_MAX_PARALLEL_RUNS"
trap parallel_exec_cleanup INT TERM

parallel_exec_submit "cifar100.independent" run_locked_job "cifar100_cifarstem_independent_v1" "cifar100.independent" "$LOG_DIR/independent.log" env \
  "${COMMON_CLASSIFICATION_ENV[@]}" \
  OUTPUT_DIR="$INDEPENDENT_OUTPUT_DIR" \
  METHODS="${METHODS:-independent}" \
  BATCH_SIZE="${BATCH_SIZE:-1536}" \
  NUM_WORKERS="${NUM_WORKERS:-4}" \
  INIT_CHECKPOINT_TEMPLATE="$POOL_TEMPLATE" \
  bash "$ROOT_DIR/scripts/common/run_core_classification.sh"

parallel_exec_submit "cifar100.dml" run_locked_job "cifar100_cifarstem_dml_v1" "cifar100.dml" "$LOG_DIR/dml.log" env \
  "${COMMON_CLASSIFICATION_ENV[@]}" \
  OUTPUT_DIR="$DML_OUTPUT_DIR" \
  METHODS="${METHODS:-dml}" \
  BATCH_SIZE="${BATCH_SIZE:-768}" \
  NUM_WORKERS="${NUM_WORKERS:-4}" \
  INIT_CHECKPOINT_TEMPLATE="$POOL_TEMPLATE" \
  PEER_INIT_CHECKPOINT_TEMPLATE="$POOL_TEMPLATE" \
  DISTILL_TEMPERATURE="${DISTILL_TEMPERATURE:-6.0}" \
  LAMBDA_IMITATION="${LAMBDA_IMITATION:-0.04}" \
  MARGIN="${MARGIN:-0.0}" \
  bash "$ROOT_DIR/scripts/common/run_core_classification.sh"

parallel_exec_submit "cifar100.ssml" run_locked_job "cifar100_oxtra42_cifarstem_v1" "cifar100.ssml" "$LOG_DIR/ssml.log" env \
  "${COMMON_CLASSIFICATION_ENV[@]}" \
  OUTPUT_DIR="$SSML_OUTPUT_DIR" \
  METHODS="${METHODS:-ssml}" \
  BATCH_SIZE="${BATCH_SIZE:-768}" \
  NUM_WORKERS="${NUM_WORKERS:-4}" \
  INIT_CHECKPOINT_TEMPLATE="$POOL_TEMPLATE" \
  PEER_INIT_CHECKPOINT_TEMPLATE="$POOL_TEMPLATE" \
  DISTILL_TEMPERATURE="${DISTILL_TEMPERATURE:-6.0}" \
  SSML_GUIDANCE_MODE="${SSML_GUIDANCE_MODE:-hybrid}" \
  SSML_GATE_SCORE_MODE="${SSML_GATE_SCORE_MODE:-useful_hard_sample_confident}" \
  SSML_TOPK_RATIO="${SSML_TOPK_RATIO:-0.42}" \
  SSML_TOPK_RATIO_START="${SSML_TOPK_RATIO_START:-0.42}" \
  SSML_TOPK_RATIO_END="${SSML_TOPK_RATIO_END:-0.42}" \
  SSML_TOPK_RAMP_START_EPOCH="${SSML_TOPK_RAMP_START_EPOCH:-12}" \
  SSML_TOPK_RAMP_END_EPOCH="${SSML_TOPK_RAMP_END_EPOCH:-36}" \
  SSML_SUPERVISED_HOTSPOT_ALPHA="${SSML_SUPERVISED_HOTSPOT_ALPHA:-0.020}" \
  LAMBDA_IMITATION="${LAMBDA_IMITATION:-0.018}" \
  MARGIN="${MARGIN:-0.0}" \
  SSML_PEER_CORRECT_ONLY="${SSML_PEER_CORRECT_ONLY:-1}" \
  SSML_STUDENT_INCORRECT_ONLY="${SSML_STUDENT_INCORRECT_ONLY:-1}" \
  SSML_PEER_TRUE_PROB_THRESHOLD="${SSML_PEER_TRUE_PROB_THRESHOLD:-0.42}" \
  SSML_PEER_TRUE_PROB_THRESHOLD_START="${SSML_PEER_TRUE_PROB_THRESHOLD_START:-0.42}" \
  SSML_PEER_TRUE_PROB_THRESHOLD_END="${SSML_PEER_TRUE_PROB_THRESHOLD_END:-0.42}" \
  SSML_PEER_STUDENT_PROB_GAP_MIN="${SSML_PEER_STUDENT_PROB_GAP_MIN:-0.01}" \
  SSML_PEER_STUDENT_PROB_GAP_MIN_START="${SSML_PEER_STUDENT_PROB_GAP_MIN_START:-0.01}" \
  SSML_PEER_STUDENT_PROB_GAP_MIN_END="${SSML_PEER_STUDENT_PROB_GAP_MIN_END:-0.01}" \
  SSML_CLASS_BALANCED_TOPK="${SSML_CLASS_BALANCED_TOPK:-1}" \
  SSML_PER_CLASS_BUDGET="${SSML_PER_CLASS_BUDGET:-18}" \
  SSML_ANCHOR_WEIGHT="${SSML_ANCHOR_WEIGHT:-0.0002}" \
  SSML_STUDENT_TRUE_PROB_MAX="${SSML_STUDENT_TRUE_PROB_MAX:-0.93}" \
  SSML_AUG_CONSISTENCY_WEIGHT="${SSML_AUG_CONSISTENCY_WEIGHT:-1.25}" \
  SSML_AUG_CONSISTENCY_SHIFT="${SSML_AUG_CONSISTENCY_SHIFT:-3}" \
  SSML_AUG_CONSISTENCY_FLIP_PROB="${SSML_AUG_CONSISTENCY_FLIP_PROB:-0.50}" \
  SSML_AUG_CONSISTENCY_NOISE_STD="${SSML_AUG_CONSISTENCY_NOISE_STD:-0.04}" \
  SSML_PEER_AUG_CONSISTENCY_MIN="${SSML_PEER_AUG_CONSISTENCY_MIN:-0.0}" \
  SSML_STUDENT_AUG_CONSISTENCY_MAX="${SSML_STUDENT_AUG_CONSISTENCY_MAX:-1.0}" \
  SSML_PEER_STUDENT_AUG_CONSISTENCY_GAP_MIN="${SSML_PEER_STUDENT_AUG_CONSISTENCY_GAP_MIN:-0.0}" \
  WARMUP_EPOCHS="${WARMUP_EPOCHS:-12}" \
  IMITATION_DECAY_START_EPOCH="${IMITATION_DECAY_START_EPOCH:-18}" \
  IMITATION_DECAY_END_EPOCH="${IMITATION_DECAY_END_EPOCH:-36}" \
  IMITATION_DECAY_MIN_SCALE="${IMITATION_DECAY_MIN_SCALE:-0.25}" \
  SSML_DISAGREEMENT_FLOOR_RATIO="${SSML_DISAGREEMENT_FLOOR_RATIO:-0.0}" \
  SSML_DEFICIT_EMA_MOMENTUM="${SSML_DEFICIT_EMA_MOMENTUM:-0.0}" \
  SSML_EXTRA_CLASS_BUDGET_SCALE="${SSML_EXTRA_CLASS_BUDGET_SCALE:-0.0}" \
  SSML_COMPLEMENT_RAMP_START_EPOCH="${SSML_COMPLEMENT_RAMP_START_EPOCH:--1}" \
  SSML_COMPLEMENT_RAMP_END_EPOCH="${SSML_COMPLEMENT_RAMP_END_EPOCH:--1}" \
  SSML_SECONDARY_PEER_AGREEMENT_MIN="${SSML_SECONDARY_PEER_AGREEMENT_MIN:-0.0}" \
  bash "$ROOT_DIR/scripts/common/run_core_classification.sh"

parallel_exec_wait_all
