#!/usr/bin/env bash
set -euo pipefail

source "$(cd "$(dirname "${BASH_SOURCE[0]}")/../common" && pwd)/_common.sh"

BASELINE_OUTPUT_DIR="${BASELINE_OUTPUT_DIR:-$ROOT_DIR/results/time_series_electricity_followup_v1/best_known}"
CORRECTIVE_OUTPUT_DIR="${CORRECTIVE_OUTPUT_DIR:-$ROOT_DIR/results/time_series_electricity_corrective_v1/corr_gate64_l15_sp5e4}"
LOG_DIR="${LOG_DIR:-$ROOT_DIR/logs/electricity}"
CUDA_DEVICES="${CUDA_VISIBLE_DEVICES:-${GPU:-0}}"
CORRECTIVE_INIT_TEMPLATE="${INIT_CHECKPOINT_TEMPLATE:-}"
CORRECTIVE_PEER_INIT_TEMPLATE="${PEER_INIT_CHECKPOINT_TEMPLATE:-}"

if [[ -z "$CORRECTIVE_INIT_TEMPLATE" ]]; then
  CORRECTIVE_INIT_TEMPLATE="$BASELINE_OUTPUT_DIR/time_series/{dataset}/{model}_independent_{regression_imitation_loss}_seed{seed}/model.pt"
fi
if [[ -z "$CORRECTIVE_PEER_INIT_TEMPLATE" ]]; then
  CORRECTIVE_PEER_INIT_TEMPLATE="$BASELINE_OUTPUT_DIR/time_series/{dataset}/{model}_independent_{regression_imitation_loss}_seed{seed}/model.pt"
fi

run_locked_job "electricity_best_known" "electricity.baseline" "$LOG_DIR/baseline.log" env \
  CUDA_VISIBLE_DEVICES="$CUDA_DEVICES" \
  OUTPUT_DIR="$BASELINE_OUTPUT_DIR" \
  DATASETS="${DATASETS:-electricity}" \
  METHODS="${METHODS:-independent dml ssml}" \
  MODEL_PAIRS="${MODEL_PAIRS:-transformer:dlinear}" \
  INDEPENDENT_MODELS="${INDEPENDENT_MODELS:-transformer dlinear}" \
  REQUIRE_DISTINCT_PEER="${REQUIRE_DISTINCT_PEER:-1}" \
  SEEDS="${SEEDS:-0 1 2}" \
  EPOCHS="${EPOCHS:-60}" \
  BATCH_SIZE="${BATCH_SIZE:-64}" \
  NUM_WORKERS="${NUM_WORKERS:-4}" \
  DEVICE="${DEVICE:-cuda}" \
  LR="${LR:-1e-3}" \
  WEIGHT_DECAY="${WEIGHT_DECAY:-0.0}" \
  SEQ_LEN="${SEQ_LEN:-96}" \
  PRED_LENS="${PRED_LENS:-24}" \
  FEATURE_MODE="${FEATURE_MODE:-multivariate}" \
  REGRESSION_IMITATION_LOSS="${REGRESSION_IMITATION_LOSS:-mse}" \
  LAMBDA_IMITATION="${LAMBDA_IMITATION:-0.30}" \
  MARGIN="${MARGIN:-0.05}" \
  WARMUP_EPOCHS="${WARMUP_EPOCHS:-5}" \
  IMITATION_DECAY_START_EPOCH="${IMITATION_DECAY_START_EPOCH:-20}" \
  IMITATION_DECAY_END_EPOCH="${IMITATION_DECAY_END_EPOCH:-50}" \
  IMITATION_DECAY_MIN_SCALE="${IMITATION_DECAY_MIN_SCALE:-0.10}" \
  HETERO_SSML_ONE_WAY="${HETERO_SSML_ONE_WAY:-1}" \
  SSML_TOPK_RATIO="${SSML_TOPK_RATIO:-0.30}" \
  bash "$ROOT_DIR/scripts/common/run_core_time_series.sh"

run_locked_job "electricity_corr_gate64_l15_sp5e4" "electricity.corrective" "$LOG_DIR/corrective.log" env \
  CUDA_VISIBLE_DEVICES="$CUDA_DEVICES" \
  OUTPUT_DIR="$CORRECTIVE_OUTPUT_DIR" \
  DATASETS="${DATASETS:-electricity}" \
  METHODS="${METHODS:-ssml}" \
  MODEL_PAIRS="${MODEL_PAIRS:-transformer:dlinear}" \
  REQUIRE_DISTINCT_PEER="${REQUIRE_DISTINCT_PEER:-1}" \
  SEEDS="${SEEDS:-0 1 2}" \
  EPOCHS="${EPOCHS:-60}" \
  BATCH_SIZE="${BATCH_SIZE:-64}" \
  NUM_WORKERS="${NUM_WORKERS:-4}" \
  DEVICE="${DEVICE:-cuda}" \
  LR="${LR:-1e-3}" \
  WEIGHT_DECAY="${WEIGHT_DECAY:-0.0}" \
  SEQ_LEN="${SEQ_LEN:-96}" \
  PRED_LENS="${PRED_LENS:-24}" \
  FEATURE_MODE="${FEATURE_MODE:-multivariate}" \
  REGRESSION_IMITATION_LOSS="${REGRESSION_IMITATION_LOSS:-mse}" \
  INIT_CHECKPOINT_TEMPLATE="$CORRECTIVE_INIT_TEMPLATE" \
  PEER_INIT_CHECKPOINT_TEMPLATE="$CORRECTIVE_PEER_INIT_TEMPLATE" \
  LAMBDA_IMITATION="${LAMBDA_IMITATION:-0.15}" \
  WARMUP_EPOCHS="${WARMUP_EPOCHS:-0}" \
  IMITATION_DECAY_START_EPOCH="${IMITATION_DECAY_START_EPOCH:-30}" \
  IMITATION_DECAY_END_EPOCH="${IMITATION_DECAY_END_EPOCH:-60}" \
  IMITATION_DECAY_MIN_SCALE="${IMITATION_DECAY_MIN_SCALE:-0.25}" \
  SSML_GUIDANCE_MODE="${SSML_GUIDANCE_MODE:-corrective}" \
  SSML_STUDENT_ONLY="${SSML_STUDENT_ONLY:-1}" \
  SSML_FREEZE_PEER="${SSML_FREEZE_PEER:-1}" \
  SSML_CORRECTION_THRESHOLD="${SSML_CORRECTION_THRESHOLD:-0.5}" \
  SSML_CORRECTION_SPARSITY_WEIGHT="${SSML_CORRECTION_SPARSITY_WEIGHT:-0.0005}" \
  SSML_CORRECTION_GATE_HIDDEN_DIM="${SSML_CORRECTION_GATE_HIDDEN_DIM:-64}" \
  SSML_CORRECTION_GATE_DROPOUT="${SSML_CORRECTION_GATE_DROPOUT:-0.0}" \
  bash "$ROOT_DIR/scripts/common/run_core_time_series.sh"
