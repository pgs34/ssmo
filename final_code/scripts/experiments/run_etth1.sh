#!/usr/bin/env bash
set -euo pipefail

source "$(cd "$(dirname "${BASH_SOURCE[0]}")/../common" && pwd)/_common.sh"

INDEPENDENT_OUTPUT_DIR="${INDEPENDENT_OUTPUT_DIR:-$ROOT_DIR/results/time_series_etth1_independent_rerun_20260405_v1}"
DML_OUTPUT_DIR="${DML_OUTPUT_DIR:-$ROOT_DIR/results/time_series_etth1_all_methods_long_v3}"
SSML_OUTPUT_DIR="${SSML_OUTPUT_DIR:-$ROOT_DIR/results/time_series_etth1_teacher_ft_v1/tft_tail10_reg15_l010_lr2e4}"
LOG_DIR="${LOG_DIR:-$ROOT_DIR/logs/etth1}"
CUDA_DEVICES="${CUDA_VISIBLE_DEVICES:-${GPU:-0}}"
SSML_INIT_TEMPLATE="${INIT_CHECKPOINT_TEMPLATE:-}"
SSML_PEER_INIT_TEMPLATE="${PEER_INIT_CHECKPOINT_TEMPLATE:-}"
ETTH1_STAGE_MAX_PARALLEL_RUNS="${ETTH1_STAGE_MAX_PARALLEL_RUNS:-all}"

if [[ -z "$SSML_INIT_TEMPLATE" ]]; then
  SSML_INIT_TEMPLATE="$INDEPENDENT_OUTPUT_DIR/time_series/{dataset}/{model}_independent_huber_seed{seed}/best_model.pt"
fi
if [[ -z "$SSML_PEER_INIT_TEMPLATE" ]]; then
  SSML_PEER_INIT_TEMPLATE="$INDEPENDENT_OUTPUT_DIR/time_series/{dataset}/{model}_independent_huber_seed{seed}/best_model.pt"
fi

parallel_exec_init "$ETTH1_STAGE_MAX_PARALLEL_RUNS"
trap parallel_exec_cleanup INT TERM

parallel_exec_submit "etth1.independent" run_locked_job "etth1_independent_rerun_20260405_v1" "etth1.independent" "$LOG_DIR/independent.log" env \
  CUDA_VISIBLE_DEVICES="$CUDA_DEVICES" \
  OUTPUT_DIR="$INDEPENDENT_OUTPUT_DIR" \
  DATASETS="${DATASETS:-etth1}" \
  METHODS="${METHODS:-independent}" \
  MODEL_PAIRS="${MODEL_PAIRS:-transformer:dlinear}" \
  INDEPENDENT_MODELS="${INDEPENDENT_MODELS:-transformer dlinear}" \
  SEEDS="${SEEDS:-0 1 2 3 4 5}" \
  EPOCHS="${EPOCHS:-80}" \
  BATCH_SIZE="${BATCH_SIZE:-64}" \
  NUM_WORKERS="${NUM_WORKERS:-4}" \
  DEVICE="${DEVICE:-cuda}" \
  LR="${LR:-1e-3}" \
  WEIGHT_DECAY="${WEIGHT_DECAY:-0.0}" \
  SEQ_LEN="${SEQ_LEN:-96}" \
  PRED_LENS="${PRED_LENS:-24}" \
  FEATURE_MODE="${FEATURE_MODE:-multivariate}" \
  REGRESSION_IMITATION_LOSS="${REGRESSION_IMITATION_LOSS:-huber}" \
  LAMBDA_IMITATION="${LAMBDA_IMITATION:-0.001}" \
  MARGIN="${MARGIN:-0.02}" \
  WARMUP_EPOCHS="${WARMUP_EPOCHS:-8}" \
  IMITATION_DECAY_START_EPOCH="${IMITATION_DECAY_START_EPOCH:-20}" \
  IMITATION_DECAY_END_EPOCH="${IMITATION_DECAY_END_EPOCH:-70}" \
  IMITATION_DECAY_MIN_SCALE="${IMITATION_DECAY_MIN_SCALE:-0.15}" \
  SSML_TOPK_RATIO="${SSML_TOPK_RATIO:-0.02}" \
  SSML_SUPERVISED_HOTSPOT_ALPHA="${SSML_SUPERVISED_HOTSPOT_ALPHA:-0.5}" \
  SSML_GATE_SCORE_MODE="${SSML_GATE_SCORE_MODE:-peer_better_student_error}" \
  SSML_SCORE_TRANSFORM="${SSML_SCORE_TRANSFORM:-none}" \
  SSML_GUIDANCE_MODE="${SSML_GUIDANCE_MODE:-reweight_only}" \
  HETERO_SSML_ONE_WAY="${HETERO_SSML_ONE_WAY:-1}" \
  EARLY_STOP_PATIENCE="${EARLY_STOP_PATIENCE:-0}" \
  bash "$ROOT_DIR/scripts/common/run_core_time_series.sh"

parallel_exec_submit "etth1.dml" run_locked_job "etth1_all_methods_long_v3" "etth1.dml" "$LOG_DIR/dml.log" env \
  CUDA_VISIBLE_DEVICES="$CUDA_DEVICES" \
  OUTPUT_DIR="$DML_OUTPUT_DIR" \
  DATASETS="${DATASETS:-etth1}" \
  METHODS="${METHODS:-dml}" \
  MODEL_PAIRS="${MODEL_PAIRS:-transformer:dlinear}" \
  REQUIRE_DISTINCT_PEER="${REQUIRE_DISTINCT_PEER:-1}" \
  SEEDS="${SEEDS:-0 1 2 3 4 5}" \
  EPOCHS="${EPOCHS:-80}" \
  BATCH_SIZE="${BATCH_SIZE:-64}" \
  NUM_WORKERS="${NUM_WORKERS:-4}" \
  DEVICE="${DEVICE:-cuda}" \
  LR="${LR:-1e-3}" \
  WEIGHT_DECAY="${WEIGHT_DECAY:-0.0}" \
  SEQ_LEN="${SEQ_LEN:-96}" \
  PRED_LENS="${PRED_LENS:-24}" \
  FEATURE_MODE="${FEATURE_MODE:-multivariate}" \
  REGRESSION_IMITATION_LOSS="${REGRESSION_IMITATION_LOSS:-huber}" \
  LAMBDA_IMITATION="${LAMBDA_IMITATION:-0.001}" \
  MARGIN="${MARGIN:-0.02}" \
  WARMUP_EPOCHS="${WARMUP_EPOCHS:-8}" \
  IMITATION_DECAY_START_EPOCH="${IMITATION_DECAY_START_EPOCH:-20}" \
  IMITATION_DECAY_END_EPOCH="${IMITATION_DECAY_END_EPOCH:-70}" \
  IMITATION_DECAY_MIN_SCALE="${IMITATION_DECAY_MIN_SCALE:-0.15}" \
  SSML_TOPK_RATIO="${SSML_TOPK_RATIO:-0.02}" \
  SSML_SUPERVISED_HOTSPOT_ALPHA="${SSML_SUPERVISED_HOTSPOT_ALPHA:-0.5}" \
  SSML_GATE_SCORE_MODE="${SSML_GATE_SCORE_MODE:-peer_better_student_error}" \
  SSML_SCORE_TRANSFORM="${SSML_SCORE_TRANSFORM:-none}" \
  SSML_GUIDANCE_MODE="${SSML_GUIDANCE_MODE:-reweight_only}" \
  HETERO_SSML_ONE_WAY="${HETERO_SSML_ONE_WAY:-1}" \
  EARLY_STOP_PATIENCE="${EARLY_STOP_PATIENCE:-0}" \
  bash "$ROOT_DIR/scripts/common/run_core_time_series.sh"

parallel_exec_wait_all

parallel_exec_init "$ETTH1_STAGE_MAX_PARALLEL_RUNS"
parallel_exec_submit "etth1.ssml" run_locked_job "etth1_teacher_ft_tft_tail10_reg15_l010_lr2e4" "etth1.ssml" "$LOG_DIR/ssml.log" env \
  CUDA_VISIBLE_DEVICES="$CUDA_DEVICES" \
  OUTPUT_DIR="$SSML_OUTPUT_DIR" \
  DATASETS="${DATASETS:-etth1}" \
  METHODS="${METHODS:-ssml}" \
  MODEL_PAIRS="${MODEL_PAIRS:-transformer:dlinear}" \
  REQUIRE_DISTINCT_PEER="${REQUIRE_DISTINCT_PEER:-1}" \
  SEEDS="${SEEDS:-0 1 2}" \
  EPOCHS="${EPOCHS:-90}" \
  BATCH_SIZE="${BATCH_SIZE:-768}" \
  NUM_WORKERS="${NUM_WORKERS:-4}" \
  DEVICE="${DEVICE:-cuda}" \
  LR="${LR:-0.0002}" \
  WEIGHT_DECAY="${WEIGHT_DECAY:-0.0}" \
  SEQ_LEN="${SEQ_LEN:-96}" \
  PRED_LENS="${PRED_LENS:-24}" \
  FEATURE_MODE="${FEATURE_MODE:-multivariate}" \
  REGRESSION_IMITATION_LOSS="${REGRESSION_IMITATION_LOSS:-huber}" \
  INIT_CHECKPOINT_TEMPLATE="$SSML_INIT_TEMPLATE" \
  PEER_INIT_CHECKPOINT_TEMPLATE="$SSML_PEER_INIT_TEMPLATE" \
  LAMBDA_IMITATION="${LAMBDA_IMITATION:-0.010}" \
  WARMUP_EPOCHS="${WARMUP_EPOCHS:-5}" \
  IMITATION_DECAY_START_EPOCH="${IMITATION_DECAY_START_EPOCH:-28}" \
  IMITATION_DECAY_END_EPOCH="${IMITATION_DECAY_END_EPOCH:-70}" \
  IMITATION_DECAY_MIN_SCALE="${IMITATION_DECAY_MIN_SCALE:-0.40}" \
  SSML_GUIDANCE_MODE="${SSML_GUIDANCE_MODE:-corrective}" \
  SSML_EVAL_OUTPUT_MODE="${SSML_EVAL_OUTPUT_MODE:-best_branch}" \
  SSML_STUDENT_ONLY="${SSML_STUDENT_ONLY:-1}" \
  SSML_FREEZE_PEER="${SSML_FREEZE_PEER:-1}" \
  SSML_CORRECTION_ONLY="${SSML_CORRECTION_ONLY:-1}" \
  SSML_CORRECTION_FEATURE_MODE="${SSML_CORRECTION_FEATURE_MODE:-trend_residual}" \
  SSML_CORRECTION_USE_REGIME_FEATURES="${SSML_CORRECTION_USE_REGIME_FEATURES:-1}" \
  SSML_CORRECTION_FREEZE_STUDENT_EPOCHS="${SSML_CORRECTION_FREEZE_STUDENT_EPOCHS:-0}" \
  SSML_CORRECTION_SPARSITY_WEIGHT="${SSML_CORRECTION_SPARSITY_WEIGHT:-0.00001}" \
  SSML_CORRECTION_GATE_HIDDEN_DIM="${SSML_CORRECTION_GATE_HIDDEN_DIM:-64}" \
  SSML_CORRECTION_GATE_DROPOUT="${SSML_CORRECTION_GATE_DROPOUT:-0.0}" \
  SSML_CORRECTION_INIT_BIAS="${SSML_CORRECTION_INIT_BIAS:--0.20}" \
  SSML_CORRECTION_RAMP_START_EPOCH="${SSML_CORRECTION_RAMP_START_EPOCH:-10}" \
  SSML_CORRECTION_RAMP_END_EPOCH="${SSML_CORRECTION_RAMP_END_EPOCH:-26}" \
  SSML_CORRECTION_TAIL_START_RATIO="${SSML_CORRECTION_TAIL_START_RATIO:-0.10}" \
  SSML_CORRECTION_REGIME_FOCUS_QUANTILE="${SSML_CORRECTION_REGIME_FOCUS_QUANTILE:-0.15}" \
  SSML_CORRECTION_FOCUS_LOSS_ALPHA="${SSML_CORRECTION_FOCUS_LOSS_ALPHA:-0.15}" \
  SSML_CORRECTION_DECOMPOSITION_KERNEL="${SSML_CORRECTION_DECOMPOSITION_KERNEL:-13}" \
  SSML_ANCHOR_WEIGHT="${SSML_ANCHOR_WEIGHT:-0.05}" \
  bash "$ROOT_DIR/scripts/common/run_core_time_series.sh"

parallel_exec_wait_all
